import {
  CatalogModel,
  ChatMessage,
  DeployRequest,
  DeployStreamEvent,
  RunnerCodeResponse,
  ServerStatusResponse,
} from '../types/api';
import { FALLBACK_CATALOG } from '../data/fallbackCatalog';

export const DEMO_MODE_URL = 'demo://colab-t4-simulator';

function normalizeBaseUrl(raw: string): string {
  return raw.trim().replace(/\/+$/, '');
}

function buildHeaders(extra?: Record<string, string>): Record<string, string> {
  return {
    'ngrok-skip-browser-warning': 'true',
    Accept: 'application/json',
    ...extra,
  };
}

// In-memory state for optional Demo Simulator so users can preview the full flow before opening Colab
let demoState: {
  activeModel: string | null;
  ollamaRunning: boolean;
  ollamaVersion: string;
  numCtx: number;
  keepAlive: string;
  installed: { name: string; size_gb: number }[];
  updatedAt: string;
} = {
  activeModel: null,
  ollamaRunning: false,
  ollamaVersion: '0.6.2',
  numCtx: 4096,
  keepAlive: '15m',
  installed: [],
  updatedAt: new Date().toISOString(),
};

function buildDemoScript(model: string, ver: string, ctx: number, keepAlive: string): string {
  return `#!/usr/bin/env bash
# ==============================================================================
# Auto-Generated by Ollama Cloud Runner (Google Colab Backend)
# Updated At : ${demoState.updatedAt}
# Target Model: ${model}
# Ollama Ver  : ${ver}
# ==============================================================================
set -euo pipefail

export OLLAMA_HOST="127.0.0.1:11434"
export OLLAMA_ORIGINS="*"
export OLLAMA_KEEP_ALIVE="${keepAlive}"
export OLLAMA_FLASH_ATTENTION="1"
export OLLAMA_NUM_CTX="${ctx}"

if ! command -v ollama >/dev/null 2>&1; then
  curl -fsSL https://ollama.com/install.sh | ${ver !== 'latest' ? `OLLAMA_VERSION="${ver}" ` : ''}sh
fi

nohup ollama serve > "/content/ollama_runner/ollama_server.log" 2>&1 &
ollama pull "${model}"`;
}

export async function fetchColabStatus(
  baseUrl: string
): Promise<{ status: ServerStatusResponse; latencyMs: number }> {
  const cleanUrl = normalizeBaseUrl(baseUrl);
  const start = performance.now();

  if (cleanUrl === DEMO_MODE_URL) {
    await new Promise((r) => setTimeout(r, 120));
    return {
      latencyMs: Math.round(performance.now() - start),
      status: {
        connected: true,
        state: demoState.ollamaRunning && demoState.activeModel ? 'ready' : 'idle',
        state_message: demoState.activeModel
          ? `Active & serving ${demoState.activeModel} (Demo Colab Simulator)`
          : 'Simulated Colab T4 GPU connected — select an Ollama model to start',
        ollama_installed: true,
        ollama_running: demoState.ollamaRunning,
        ollama_version: demoState.ollamaVersion,
        configured_ollama_version: demoState.ollamaVersion,
        active_model: demoState.activeModel,
        loaded_models: demoState.activeModel ? [demoState.activeModel] : [],
        installed_models: demoState.installed.map((m) => ({
          name: m.name,
          size_bytes: m.size_gb * 1024 ** 3,
          size_gb: m.size_gb,
          family: m.name.split(':')[0],
        })),
        gpu: {
          available: true,
          name: 'Tesla T4 (Simulated Colab)',
          vram_total_mb: 15360,
          vram_used_mb: demoState.activeModel ? 5640 : 410,
          utilization_percent: demoState.activeModel ? 18 : 2,
          driver_version: '550.54.15',
        },
        system: {
          cpu_percent: 14.2,
          ram_total_gb: 12.67,
          ram_used_gb: demoState.activeModel ? 4.35 : 1.92,
          disk_free_gb: 68.4,
          disk_total_gb: 107.7,
          platform_name: 'Linux Colab Simulator',
          is_colab: true,
        },
        ngrok_url: DEMO_MODE_URL,
        uptime_seconds: 420,
        last_updated_script_at: demoState.updatedAt,
      },
    };
  }

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 7000);
  try {
    const resp = await fetch(`${cleanUrl}/api/status`, {
      headers: buildHeaders(),
      signal: controller.signal,
    });
    if (!resp.ok) {
      throw new Error(`HTTP ${resp.status}: ${resp.statusText}`);
    }
    const data = (await resp.json()) as ServerStatusResponse;
    return {
      status: data,
      latencyMs: Math.round(performance.now() - start),
    };
  } finally {
    clearTimeout(timer);
  }
}

export async function fetchModelCatalog(baseUrl: string): Promise<CatalogModel[]> {
  const cleanUrl = normalizeBaseUrl(baseUrl);
  if (!cleanUrl || cleanUrl === DEMO_MODE_URL) {
    const installedBases = new Set(demoState.installed.map((m) => m.name.split(':')[0]));
    return FALLBACK_CATALOG.map((m) => ({
      ...m,
      is_installed: installedBases.has(m.name),
    }));
  }

  const resp = await fetch(`${cleanUrl}/api/models/catalog`, {
    headers: buildHeaders(),
  });
  if (!resp.ok) {
    return FALLBACK_CATALOG;
  }
  const payload = (await resp.json()) as { models?: CatalogModel[] };
  return payload.models && payload.models.length > 0 ? payload.models : FALLBACK_CATALOG;
}

export async function fetchRunnerCode(baseUrl: string): Promise<RunnerCodeResponse> {
  const cleanUrl = normalizeBaseUrl(baseUrl);
  if (cleanUrl === DEMO_MODE_URL) {
    const targetModel = demoState.activeModel || 'llama3:8b';
    return {
      script_path: '/content/ollama_runner/start_ollama.sh',
      config_path: '/content/ollama_runner/runner_config.json',
      log_path: '/content/ollama_runner/ollama_server.log',
      script: buildDemoScript(
        targetModel,
        demoState.ollamaVersion,
        demoState.numCtx,
        demoState.keepAlive
      ),
      config: {
        model: targetModel,
        ollama_version: demoState.ollamaVersion,
        num_ctx: demoState.numCtx,
        keep_alive: demoState.keepAlive,
        updated_at: demoState.updatedAt,
      },
      logs: demoState.ollamaRunning
        ? `time=${demoState.updatedAt} level=INFO msg="Listening on 127.0.0.1:11434 (version ${demoState.ollamaVersion})"\ntime=${demoState.updatedAt} level=INFO msg="GPU detected: NVIDIA Tesla T4 (15.0 GiB VRAM)"\ntime=${demoState.updatedAt} level=INFO msg="Loaded model ${targetModel} onto CUDA0"`
        : 'Ollama daemon has not been started yet.',
      last_updated_at: demoState.updatedAt,
    };
  }

  const resp = await fetch(`${cleanUrl}/api/server/code`, {
    headers: buildHeaders(),
  });
  if (!resp.ok) {
    throw new Error(`Failed to fetch server code (${resp.status})`);
  }
  return (await resp.json()) as RunnerCodeResponse;
}

export async function deployModelToColab(
  baseUrl: string,
  req: DeployRequest,
  onEvent: (evt: DeployStreamEvent) => void
): Promise<void> {
  const cleanUrl = normalizeBaseUrl(baseUrl);

  if (cleanUrl === DEMO_MODE_URL) {
    const steps: DeployStreamEvent[] = [
      {
        step: 'code_updated',
        message: `Updated Colab runner code (/content/ollama_runner/start_ollama.sh) for '${req.model}'`,
        progress: 18,
      },
      {
        step: 'ollama_verified',
        message: `Verified Ollama engine (${req.ollama_version === 'latest' ? 'v0.6.2' : req.ollama_version}) on Colab VM`,
        progress: 35,
      },
      {
        step: 'starting_daemon',
        message: 'Started `ollama serve` daemon on Colab Tesla T4 GPU (port 11434)',
        progress: 50,
      },
      {
        step: 'pull_progress',
        message: `Downloading ${req.model} layers: 2,410 MB / 4,661 MB (51.7%)`,
        progress: 72,
        download_percent: 51.7,
      },
      {
        step: 'pull_progress',
        message: `Downloading ${req.model} layers: 4,661 MB / 4,661 MB (100%)`,
        progress: 90,
        download_percent: 100,
      },
      {
        step: 'warming_up',
        message: `Loading '${req.model}' weights into Tesla T4 VRAM...`,
        progress: 96,
      },
    ];

    for (const s of steps) {
      await new Promise((r) => setTimeout(r, 480));
      onEvent(s);
    }

    demoState = {
      activeModel: req.model,
      ollamaRunning: true,
      ollamaVersion: req.ollama_version === 'latest' ? '0.6.2' : req.ollama_version,
      numCtx: req.num_ctx,
      keepAlive: req.keep_alive,
      installed: demoState.installed.some((m) => m.name === req.model)
        ? demoState.installed
        : [...demoState.installed, { name: req.model, size_gb: 4.7 }],
      updatedAt: new Date().toISOString(),
    };

    await new Promise((r) => setTimeout(r, 320));
    onEvent({
      step: 'ready',
      message: `Colab server updated and serving '${req.model}' via ngrok!`,
      progress: 100,
      active_model: req.model,
    });
    return;
  }

  const resp = await fetch(`${cleanUrl}/api/server/deploy`, {
    method: 'POST',
    headers: buildHeaders({ 'Content-Type': 'application/json' }),
    body: JSON.stringify(req),
  });

  if (!resp.ok || !resp.body) {
    const errTxt = await resp.text();
    throw new Error(errTxt || `Deploy failed (${resp.status})`);
  }

  const reader = resp.body.getReader();
  const decoder = new TextDecoder();
  let buffer = '';

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split('\n');
    buffer = lines.pop() ?? '';

    for (const line of lines) {
      if (!line.trim()) continue;
      const evt = JSON.parse(line) as DeployStreamEvent;
      onEvent(evt);
    }
  }
}

export async function stopColabOllama(baseUrl: string): Promise<void> {
  const cleanUrl = normalizeBaseUrl(baseUrl);
  if (cleanUrl === DEMO_MODE_URL) {
    demoState.ollamaRunning = false;
    demoState.activeModel = null;
    return;
  }
  await fetch(`${cleanUrl}/api/server/stop`, {
    method: 'POST',
    headers: buildHeaders(),
  });
}

export async function deleteInstalledModel(baseUrl: string, modelName: string): Promise<void> {
  const cleanUrl = normalizeBaseUrl(baseUrl);
  if (cleanUrl === DEMO_MODE_URL) {
    demoState.installed = demoState.installed.filter((m) => m.name !== modelName);
    if (demoState.activeModel === modelName) demoState.activeModel = null;
    return;
  }
  await fetch(`${cleanUrl}/api/models/${encodeURIComponent(modelName)}`, {
    method: 'DELETE',
    headers: buildHeaders(),
  });
}

export async function streamColabChat(
  baseUrl: string,
  model: string,
  messages: ChatMessage[],
  temperature: number,
  numCtx: number,
  onToken: (chunk: string) => void
): Promise<void> {
  const cleanUrl = normalizeBaseUrl(baseUrl);

  if (cleanUrl === DEMO_MODE_URL) {
    const lastUser = messages[messages.length - 1]?.content ?? '';
    const reply = `[Simulated ${model} on Colab Tesla T4]\n\nYour Colab runner config is updated and serving **${model}**. Once you paste your live \`https://xxxx.ngrok-free.app\` URL from \`Ollama_Cloud_Runner.ipynb\`, your prompt ("${lastUser.slice(0, 60)}${lastUser.length > 60 ? '...' : ''}") will execute directly on Google Colab GPU hardware!`;
    for (const word of reply.split(' ')) {
      await new Promise((r) => setTimeout(r, 35));
      onToken(word + ' ');
    }
    return;
  }

  const resp = await fetch(`${cleanUrl}/api/chat`, {
    method: 'POST',
    headers: buildHeaders({ 'Content-Type': 'application/json' }),
    body: JSON.stringify({
      model,
      messages,
      temperature,
      num_ctx: numCtx,
      stream: true,
    }),
  });

  if (!resp.ok || !resp.body) {
    throw new Error(`Chat request failed (${resp.status})`);
  }

  const reader = resp.body.getReader();
  const decoder = new TextDecoder();
  let buffer = '';

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split('\n');
    buffer = lines.pop() ?? '';

    for (const line of lines) {
      if (!line.trim()) continue;
      const parsed = JSON.parse(line) as {
        error?: string;
        message?: { content?: string };
      };
      if (parsed.error) {
        throw new Error(parsed.error);
      }
      if (parsed.message?.content) {
        onToken(parsed.message.content);
      }
    }
  }
}
